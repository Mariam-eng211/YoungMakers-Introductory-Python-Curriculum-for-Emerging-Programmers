# Print a message 5 times (counts from 0 to 4)
for i in range(5):
    print(f"Loop iteration number: {i}")

#How range() works:
#range(5) generates numbers 0, 1, 2, 3, 4 (starts at 0 by default, stops before 5).
#range(1, 6) generates numbers 1, 2, 3, 4, 5 (start, stop).
#range(2, 11, 2) generates 2, 4, 6, 8, 10 (start, stop, step size).
